const preferenceKey = 'frametracker:language';
export let language = 'ru';
try {
  if (localStorage.getItem(preferenceKey) === 'en') language = 'en';
} catch {
  // The language remains available for this session.
}

export function setLanguage(value) {
  language = value === 'en' ? 'en' : 'ru';
  try {
    localStorage.setItem(preferenceKey, language);
  } catch {
    // Storage can be disabled by the browser.
  }
}

export function t(key, values = {}) {
  return messages[key][language === 'en' ? 1 : 0].replace(/\{(\w+)\}/g, (_, name) => values[name]);
}

export function catalogText(row, field) {
  return language === 'en' ? row.en ?? row[field] : row[field];
}
